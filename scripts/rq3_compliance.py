"""RQ3 as a compliance outcome: with NO physical change, how much GEI
"reduction" does each reading of BEE's grid-factor rule show?

    python scripts/rq3_compliance.py   # data/cea/factors.csv -> docs/RQ3_COMPLIANCE.md

GEI = (combustion + electricity x factor) / production. Hold combustion,
electricity and production fixed. If electricity is a share s of the
baseline-year emissions in the target basis, then replacing the baseline
factor f_b by an assessment factor f_a changes GEI by exactly

    s x (f_a / f_b - 1)

That is arithmetic, not a model. The three readings of f_a are the ones
docs/RQ3_FINDINGS.md finds the procedure's text supports. What is ASSUMED, and
must be checked against the target notifications before this is cited:
  - which financial year is the baseline (FY2023-24 is the default here; BEE's
    procedure does not name one, see docs/RQ3_FINDINGS.md);
  - that the baseline GEI was computed with that year's first-published factor.
No plant data is used, real or synthetic.
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FACTORS = ROOT / "data" / "cea" / "factors.csv"
VERSIONS = ROOT / "data" / "cea" / "versions.csv"
OUT = ROOT / "docs" / "RQ3_COMPLIANCE.md"
GRID = "grid.weighted_avg_incl_re_captive.incl_imports"  # engine/calculate.py
BASELINES = ["FY2022-23", "FY2023-24", "FY2024-25"]
DEFAULT_BASELINE = "FY2023-24"  # UNVERIFIED: see docs/RQ3_FINDINGS.md, "Also to verify"
TARGETS = [1.0, 3.0]            # FY2025-26 GEI reduction range, percent (CLAUDE.md)
AT_DEADLINE, AFTER = "v21.0", "v22.0"  # newest version before / after 31 July 2026


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return "\n".join(lines + ["| " + " | ".join(r) + " |" for r in rows])


def share_needed(d: float, target: float) -> str:
    """Scope 2 share at which the factor alone shows a reduction of `target`."""
    if d >= 0:
        return "never (no apparent reduction)"
    s = target / -d
    return "never (would need >100%)" if s > 1 else f"{100 * s:.0f}%"


def readings(value: dict[tuple[str, str], float], first: dict[str, str],
             baseline: str) -> list[tuple[str, str, float]]:
    """(reading, factor used for the assessment year, % change vs baseline factor)."""
    f_b = value[(first[baseline], baseline)]
    newest_at_deadline = max(fy for v, fy in value if v == AT_DEADLINE)
    f_deadline = value[(AT_DEADLINE, newest_at_deadline)]
    f_after = value[(AFTER, "FY2025-26")]
    return [
        ("same factor as the baseline year (the consistency clause)",
         f"{f_b:.4f} ({first[baseline]}, {baseline})", 0.0),
        ("'latest' when reports were due",
         f"{f_deadline:.4f} ({AT_DEADLINE}, {newest_at_deadline})", 100 * (f_deadline / f_b - 1)),
        ("'latest' once the FY2025-26 factor exists",
         f"{f_after:.4f} ({AFTER}, FY2025-26)", 100 * (f_after / f_b - 1)),
    ]


def main() -> None:
    with VERSIONS.open(encoding="utf-8") as fh:
        ordinal = {v["version_label"]: int(v["version_ordinal"]) for v in csv.DictReader(fh)}
    value: dict[tuple[str, str], float] = {}
    first: dict[str, str] = {}
    with FACTORS.open(encoding="utf-8") as fh:
        for f in csv.DictReader(fh):
            if f["geography"] == "IN" and f["factor_key"] == GRID:
                v, fy = f["version_label"], f["fy"]
                value[(v, fy)] = float(f["value"])
                if fy not in first or ordinal[v] < ordinal[first[fy]]:
                    first[fy] = v

    main_rows = [[name, used, f"{d:+.2f}%"] + [share_needed(d, t) for t in TARGETS]
                 for name, used, d in readings(value, first, DEFAULT_BASELINE)]
    shares = [10, 20, 30, 40, 50, 60, 80, 100]

    def cell(s: int, d: float) -> str:
        shown = -s * d / 100 + 0.0  # reduction shown, percent (+0.0: no '-0.00')
        text = f"{shown:.2f}%"
        return f"**{text}**" if shown >= TARGETS[0] else text

    curve = [[name] + [cell(s, d) for s in shares]
             for name, _, d in readings(value, first, DEFAULT_BASELINE)]
    by_baseline = [[b, name, f"{d:+.2f}%"] + [share_needed(d, t) for t in TARGETS]
                   for b in BASELINES for name, _, d in readings(value, first, b)]

    OUT.write_text("\n\n".join([
        "# RQ3 as a compliance outcome: what each reading shows with no physical change",
        ("_Generated by `scripts/rq3_compliance.py` from `data/cea/factors.csv`. "
         "Do not edit by hand._"),
        ("Take an entity whose fuel use, electricity use and production are **identical** in "
         "the baseline year and in FY2025-26. Its emission intensity (GEI) still moves, "
         "because the grid factor applied to its electricity differs between the two years. "
         "If electricity is a share *s* of its baseline-year emissions in the target basis, "
         "the change is exactly *s* × (*f*ₐ / *f*_b − 1). This file evaluates that for the "
         "three readings of BEE's rule found in `docs/RQ3_FINDINGS.md`."),
        (f"**Assumed, not verified.** (1) The baseline year is {DEFAULT_BASELINE}; the last "
         "table repeats the calculation for neighbouring years. BEE's procedure does not "
         "name the baseline year (`docs/RQ3_FINDINGS.md`). (2) The baseline GEI used "
         "that year's factor as first published. Both must be checked against the target "
         "notifications. Factor series: `" + GRID + "`. No plant data is used; this is a "
         "property of the published factors, stated per Scope 2 share. It is not a claim "
         "about any entity's compliance."),
        f"## Baseline {DEFAULT_BASELINE}: apparent GEI change from the factor alone",
        table(["reading of the rule", "factor applied to FY2025-26", "factor change",
               "share that shows a 1% reduction", "share that shows a 3% reduction"], main_rows),
        "## GEI reduction shown, by Scope 2 share of the target basis",
        table(["reading"] + [f"s = {s}%" for s in shares], curve),
        (f"**Bold** = at or above {TARGETS[0]:.0f}%, the bottom of the FY2025-26 target range "
         f"({TARGETS[0]:.0f}–{TARGETS[1]:.0f}%)."),
        "## Reading it",
        ("- **The three readings give three different outcomes for the same plant.** Under "
         "the consistency reading the factor contributes nothing, and the whole target must "
         "come from physical change. Under the other two, part or all of the target is met "
         "by the fall in the grid factor.\n"
         "- **The size of that part depends on the Scope 2 share**, which is why this is a "
         "table and not one number. For an entity with little purchased electricity the "
         "readings barely differ.\n"
         "- **The direction is an accident of the years involved.** The grid factor fell "
         "between these years. In a year where it rises, the same readings would make "
         "targets harder to meet, by the same arithmetic.\n"
         "- **What this does not show:** whether targets were set expecting the grid factor "
         "to fall, or which reading verifiers actually applied. Both are questions for BEE "
         "and for the first cycle's verification statements."),
        "## The same calculation for other baseline years",
        table(["baseline year", "reading of the rule", "factor change",
               "share that shows a 1% reduction", "share that shows a 3% reduction"],
              by_baseline),
    ]) + "\n", encoding="utf-8", newline="\n")
    print(f"RQ3 compliance -> {OUT.relative_to(ROOT)}")
    for row in main_rows:
        print("  " + " | ".join(row))


if __name__ == "__main__":
    main()
