"""What each CEA version changed, compared with everything published before it.

    python scripts/registry_changelog.py   # data/cea/*.csv -> data/cea/CHANGELOG.md

For every version: the financial years it published for the first time, the
earlier values it restated (how many, and the largest), and the factor series
that appeared or were missing compared with the version before. All of it is
derived from factors.csv; nothing is typed in.
"""
import csv
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "cea"
OUT = DATA / "CHANGELOG.md"
RESTATED = 5e-5   # relative change below this is a rounding difference, not a restatement


def changes() -> list[dict]:
    with (DATA / "versions.csv").open(encoding="utf-8") as fh:
        versions = sorted(csv.DictReader(fh), key=lambda v: int(v["version_ordinal"]))
    by_version: dict[str, dict[tuple[str, str, str], float]] = defaultdict(dict)
    with (DATA / "factors.csv").open(encoding="utf-8") as fh:
        for f in csv.DictReader(fh):
            by_version[f["version_label"]][(f["factor_key"], f["geography"], f["fy"])] = \
                float(f["value"])

    known: dict[tuple[str, str, str], float] = {}   # the newest earlier value of each point
    seen_years: set[str] = set()
    previous_keys: set[str] = set()
    out = []
    for v in versions:
        label, values = v["version_label"], by_version[v["version_label"]]
        years = {fy for _, _, fy in values}
        keys = {key for key, _, _ in values}
        restated = [(abs(new / known[p] - 1), p, known[p], new) for p, new in values.items()
                    if p in known and known[p] and abs(new / known[p] - 1) > RESTATED]
        out.append({
            "label": label, "date": v["stated_date"], "covers": v["covers_fy"],
            "values": len(values), "new_years": sorted(years - seen_years),
            "restated": len(restated), "largest": max(restated, default=None),
            "comparable": sum(p in known for p in values),
            "added": sorted(keys - previous_keys) if previous_keys else [],
            "missing": sorted(previous_keys - keys),
        })
        known.update(values)
        seen_years |= years
        previous_keys = keys
    return out


def main() -> None:
    rows = changes()
    lines = [
        "# Changelog of the CEA registry, by version",
        "",
        "_Generated by `scripts/registry_changelog.py` from `factors.csv`. Do not edit by hand._",
        "",
        ("Each version is compared with the newest earlier value of the same factor, "
         "geography and year. A value counts as restated when it differs by more than "
         f"{RESTATED:.3%}; smaller differences are rounding."),
        "",
        "| version | dated | newest year | values | first published | restated | largest restatement |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        big = "–"
        if r["largest"]:
            _, (key, geo, fy), old, new = r["largest"]
            big = f"{100 * (new / old - 1):+.2f}% `{key}` {geo} {fy}"
        lines.append(
            f"| {r['label']} | {r['date']} | {r['covers']} | {r['values']} | "
            f"{', '.join(r['new_years']) or '–'} | {r['restated']} of {r['comparable']} | {big} |")
    lines += ["", "## Series that appeared or were missing", ""]
    for r in rows:
        if r["added"] or r["missing"]:
            lines.append(f"- **{r['label']}**"
                         + (": added " + ", ".join(f"`{k}`" for k in r["added"]) if r["added"] else ":")
                         + ("; " if r["added"] and r["missing"] else " " if r["missing"] else "")
                         + ("not in this version: " + ", ".join(f"`{k}`" for k in r["missing"])
                            if r["missing"] else ""))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    total = sum(r["restated"] for r in rows)
    print(f"changelog -> {OUT.relative_to(ROOT)}: {len(rows)} versions, {total} restatements")


if __name__ == "__main__":
    main()
