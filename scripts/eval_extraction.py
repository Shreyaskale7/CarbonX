"""Evaluate consumption_kwh extraction: rule baseline vs calibrated model, on
layouts seen in training, development layouts, and frozen-model test layouts.

    python scripts/eval_extraction.py   # -> docs/EXTRACTION_RESULTS.md

Synthetic bills only (src/carbonx/extraction/synthetic.py). Deterministic:
fixed seeds, so the results file is reproducible byte for byte. Method,
history and limits: docs/EXTRACTION.md.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from carbonx.extraction.extract import ConsumptionModel, baseline, ece, meter_id, period
from carbonx.extraction.synthetic import DEV, SEEN, TEST, Bill, corpus

OUT = ROOT / "docs" / "EXTRACTION_RESULTS.md"
PER_LAYOUT = 300


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return "\n".join(lines + ["| " + " | ".join(r) + " |" for r in rows])


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def evaluate(model: ConsumptionModel, bills: list[Bill]) -> dict:
    base = [baseline(b.text).value == b.kwh for b in bills]
    raw = [model.predict(b.text, calibrated=False) for b in bills]
    cal = [model.predict(b.text, calibrated=True) for b in bills]
    ok = [p.value == b.kwh for p, b in zip(cal, bills, strict=True)]
    return {
        "n": len(bills), "baseline": sum(base) / len(bills), "model": sum(ok) / len(bills),
        "ece_raw": ece([p.confidence for p in raw], ok),
        "ece_cal": ece([p.confidence for p in cal], ok),
        "conf_cal": sum(p.confidence for p in cal) / len(bills),
        "ok": ok, "cal": [p.confidence for p in cal],
    }


def main() -> None:
    seen = corpus(PER_LAYOUT, SEEN, seed=20260926)
    dev = corpus(PER_LAYOUT, DEV, seed=20260927)
    test = corpus(PER_LAYOUT, TEST, seed=20261004)
    train, test_seen = [], []
    for layout in SEEN:  # 80/20 by document within each training layout
        rows = [b for b in seen if b.layout == layout]
        cut = int(0.8 * len(rows))
        train, test_seen = train + rows[:cut], test_seen + rows[cut:]

    model = ConsumptionModel()
    lolo = model.fit_leave_one_layout_out(
        [b.text for b in train], [b.kwh for b in train], [b.layout for b in train])
    results = {"seen layouts": evaluate(model, test_seen),
               "development layouts (6–8)": evaluate(model, dev),
               "**test layouts (9–11)**": evaluate(model, test)}

    per_layout = []
    for group, name in ((test_seen, "seen"), (dev, "development"), (test, "**test**")):
        for layout in sorted({b.layout for b in group}):
            r = evaluate(model, [b for b in group if b.layout == layout])
            per_layout.append([f"SYNTH-DISCOM-{layout}", name, str(r["n"]),
                               pct(r["baseline"]), pct(r["model"]), pct(r["conf_cal"])])

    other = [[name, str(len(group)),
              pct(sum(period(b.text) == (b.period_start, b.period_end) for b in group)
                  / len(group)),
              pct(sum(meter_id(b.text) == b.meter_id for b in group) / len(group))]
             for name, group in (("seen layouts", test_seen),
                                 ("development layouts (6–8)", dev),
                                 ("**test layouts (9–11)**", test))]
    rt = results["**test layouts (9–11)**"]
    reliability = []
    for lo in range(10):
        idx = [i for i, c in enumerate(rt["cal"])
               if lo / 10 < c <= (lo + 1) / 10 or (lo == 0 and c == 0)]
        if idx:
            reliability.append([f"{lo / 10:.1f}–{(lo + 1) / 10:.1f}", str(len(idx)),
                                pct(sum(rt["cal"][i] for i in idx) / len(idx)),
                                pct(sum(rt["ok"][i] for i in idx) / len(idx))])

    OUT.write_text("\n\n".join([
        "# Extraction results: consumption_kwh, baseline vs calibrated model",
        "_Generated by `scripts/eval_extraction.py`. Do not edit by hand._",
        ("> **Synthetic data.** Every bill here is invented "
         "(`src/carbonx/extraction/synthetic.py`): fictional issuers, our own layouts. "
         "These numbers show how the pipeline behaves and that the evaluation is set up "
         "honestly. They are **not** accuracy on real Indian electricity bills. No real "
         "bill has been collected yet; when redacted bills arrive, this same script is "
         "re-run on them. Method, history and limits: `docs/EXTRACTION.md`."),
        (f"**Setup.** {PER_LAYOUT} bills per layout. The model trains on 80% of layouts "
         "1–5. Layouts 6–8 were unseen in training but were used for error analysis, so "
         "they are development data. **Layouts 9–11 were written after the model was "
         "frozen and are the test.** Confidence is temperature-scaled using "
         "leave-one-layout-out predictions on the training layouts, and may only be "
         f"softened, never sharpened (T = {model.temperature:.2f}). "
         f"Leave-one-layout-out accuracy on the training layouts: {pct(lolo)}."),
        "## Headline",
        table(["evaluated on", "bills", "rule baseline", "model", "ECE raw",
               "ECE calibrated", "mean confidence"],
              [[name, str(r["n"]), pct(r["baseline"]), pct(r["model"]),
                f"{r['ece_raw']:.3f}", f"{r['ece_cal']:.3f}", pct(r["conf_cal"])]
               for name, r in results.items()]),
        ("ECE = expected calibration error (0 is perfect): the gap between how confident "
         "the model is and how often it is right."),
        "## By layout",
        table(["issuer", "split", "bills", "rule baseline", "model", "mean confidence"],
              per_layout),
        "## Other fields: rules only, no model",
        ("The billing period and meter id are read by rules written from the training "
         "layouts. They have no confidence, and no model stands behind them."),
        table(["evaluated on", "bills", "billing period", "meter id"], other),
        "## Reliability on the test layouts",
        table(["confidence bin", "bills", "mean confidence", "accuracy"], reliability),
    ]) + "\n", encoding="utf-8", newline="\n")
    print(f"LOLO acc {pct(lolo)}  T={model.temperature:.2f}")
    for name, r in results.items():
        print(f"  {name}: baseline {pct(r['baseline'])} model {pct(r['model'])} "
              f"ECE {r['ece_raw']:.3f}->{r['ece_cal']:.3f} conf {pct(r['conf_cal'])}")
    for row in per_layout:
        print("    ", *row)


if __name__ == "__main__":
    main()
