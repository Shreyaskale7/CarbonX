"""Evaluate consumption_kwh extraction on REAL, redacted bills, one utility held out at a time.

    python scripts/eval_real_bills.py   # data/redacted_bills/ -> docs/EXTRACTION_REAL_RESULTS.md

For each utility (DISCOM) D: train on the synthetic training layouts plus every real bill from
the OTHER utilities, calibrate with leave-one-layout-out (each other utility is one layout),
then score on D, which the model has never seen. This is the "held out by DISCOM" test from
CLAUDE.md. It is also what a reader should ask of any number reported here: unseen utility.

It refuses to write a results file until there is enough to say something: at least
MIN_DISCOMS utilities with at least MIN_PER_DISCOM bills each. Below that, a table of
percentages would look like a finding and be noise. Every file it reads must pass
tests/test_redacted_bills.py (consent, reviewer, true consumption). Read
docs/BILL_COLLECTION.md for how bills get there.
"""
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from carbonx.extraction.extract import ConsumptionModel, baseline, ece
from carbonx.extraction.synthetic import SEEN, corpus

DIR = ROOT / "data" / "redacted_bills"
OUT = ROOT / "docs" / "EXTRACTION_REAL_RESULTS.md"
MIN_DISCOMS, MIN_PER_DISCOM = 3, 5
SYNTH_PER_LAYOUT = 100


def load(directory: Path) -> list[dict]:
    bills = []
    for txt in sorted(directory.glob("*.txt")):
        meta = json.loads(txt.with_suffix(".json").read_text(encoding="utf-8"))
        if not (meta.get("consent") is True and meta.get("reviewed_by") and meta.get("consumption_kwh")):
            sys.exit(f"{txt.name}: consent, reviewer and true consumption must be filled in the sidecar")
        bills.append({"id": meta["id"], "discom": meta["discom"], "kwh": float(meta["consumption_kwh"]),
                      "text": txt.read_text(encoding="utf-8")})
    return bills


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """95% interval for a proportion: honest about what a handful of bills can say."""
    if n == 0:
        return 0.0, 1.0
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def enough(bills: list[dict]) -> tuple[bool, str]:
    counts: dict[str, int] = {}
    for b in bills:
        counts[b["discom"]] = counts.get(b["discom"], 0) + 1
    usable = {d: n for d, n in counts.items() if n >= MIN_PER_DISCOM}
    msg = (f"{len(bills)} bills from {len(counts)} utilities {dict(sorted(counts.items()))}; "
           f"need {MIN_DISCOMS} utilities with {MIN_PER_DISCOM}+ bills each")
    return len(usable) >= MIN_DISCOMS, msg


def run(bills: list[dict], synth_per_layout: int = SYNTH_PER_LAYOUT) -> dict[str, dict]:
    synth = corpus(synth_per_layout, SEEN, seed=20260926)
    discoms = sorted({b["discom"] for b in bills if sum(x["discom"] == b["discom"] for x in bills) >= MIN_PER_DISCOM})
    out = {}
    for held in discoms:
        train = [b for b in bills if b["discom"] != held]
        texts = [s.text for s in synth] + [b["text"] for b in train]
        truths = [s.kwh for s in synth] + [b["kwh"] for b in train]
        groups = [s.layout for s in synth] + [100 + discoms.index(b["discom"]) if b["discom"] in discoms
                                              else 200 for b in train]
        model = ConsumptionModel()
        model.fit_leave_one_layout_out(texts, truths, groups)
        test = [b for b in bills if b["discom"] == held]
        pred = [model.predict(b["text"]) for b in test]
        ok = [p.value == b["kwh"] for p, b in zip(pred, test, strict=True)]
        base = [baseline(b["text"]).value == b["kwh"] for b in test]
        out[held] = {"n": len(test), "model": sum(ok), "baseline": sum(base),
                     "conf": sum(p.confidence or 0 for p in pred) / len(test),
                     "ece": ece([p.confidence or 0 for p in pred], ok),
                     "ok": ok, "confs": [p.confidence or 0 for p in pred]}
    return out


def pct(x: float) -> str:
    return f"{100 * x:.0f}%"


def report(res: dict[str, dict]) -> str:
    n = sum(r["n"] for r in res.values())
    k, kb = sum(r["model"] for r in res.values()), sum(r["baseline"] for r in res.values())
    rows = []
    for d, r in res.items():
        lo, hi = wilson(r["model"], r["n"])
        rows.append(f"| {d} | {r['n']} | {r['baseline']}/{r['n']} | {r['model']}/{r['n']} "
                    f"({pct(lo)} to {pct(hi)}) | {pct(r['conf'])} | {r['ece']:.2f} |")
    lo, hi = wilson(k, n)
    return "\n".join([
        "# Extraction on real bills, one utility held out at a time",
        "_Generated by `scripts/eval_real_bills.py`. Do not edit by hand._",
        (f"> **Read the counts first.** {n} real bills from {len(res)} utilities. Each row is a "
         "utility the model had never seen. With this few bills the intervals are wide and the "
         "calibration error is noisy; neither is a general statement about Indian electricity "
         "bills, and neither says anything about a utility that is not in this table."),
        "",
        "| held-out utility | bills | rule baseline | model (95% interval) | mean confidence | ECE |",
        "|---|---|---|---|---|---|",
        *rows,
        f"| **all** | {n} | {kb}/{n} | {k}/{n} ({pct(lo)} to {pct(hi)}) | | |",
        "",
        ("Training for each row: the synthetic layouts 1 to 5 plus all real bills from the other "
         "utilities; confidence is temperature-scaled by leave-one-layout-out over those. "
         "'Correct' means the extracted number equals the consumption a person read from the "
         "original bill. Whether invariant 6 is met (confidence usable as a probability) needs "
         "the ECE to be small on enough bills; compare with `docs/EXTRACTION_RESULTS.md`, which "
         "is synthetic."),
        ""])


def main() -> None:
    bills = load(DIR)
    ok, msg = enough(bills)
    if not ok:
        print("not enough real bills to evaluate:", msg)
        return
    res = run(bills)
    OUT.write_text(report(res), encoding="utf-8", newline="\n")
    print(f"real bills -> {OUT}: {msg}")


if __name__ == "__main__":
    main()
